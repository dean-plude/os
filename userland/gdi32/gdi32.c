#define GLYPH_W 8
#define GLYPH_H 8
#define SCALE   2
#define CELL_W  (GLYPH_W * SCALE)      /* 16 px */
#define CELL_H  (GLYPH_H * SCALE)      /* 16 px */

static NOVA_DC *dc_of(HDC h) { return (NOVA_DC *)h; }

static inline void put(NOVA_DC *d, int x, int y, COLORREF c)
{
    if (x < 0 || y < 0 || x >= d->w || y >= d->h) return;
    d->bits[(size_t)y * d->stride + x] = c & 0xFFFFFF;
}

COLORREF SetPixel(HDC h, int x, int y, COLORREF c) { NOVA_DC *d = dc_of(h); if (d) put(d, x, y, c); return c; }
COLORREF GetPixel(HDC h, int x, int y)
{
    NOVA_DC *d = dc_of(h);
    if (!d || x < 0 || y < 0 || x >= d->w || y >= d->h) return 0xFFFFFFFF;
    return d->bits[(size_t)y * d->stride + x];
}
COLORREF SetTextColor(HDC h, COLORREF c) { NOVA_DC *d = dc_of(h); COLORREF o = d ? d->text_color : 0; if (d) d->text_color = c; return o; }
COLORREF SetBkColor(HDC h, COLORREF c)   { NOVA_DC *d = dc_of(h); COLORREF o = d ? d->bk_color : 0; if (d) d->bk_color = c; return o; }
int      SetBkMode(HDC h, int m)         { NOVA_DC *d = dc_of(h); int o = d ? d->bk_mode : 0; if (d) d->bk_mode = m; return o; }

static void fill(NOVA_DC *d, int x0, int y0, int x1, int y1, COLORREF c)
{
    if (x0 < 0) x0 = 0; if (y0 < 0) y0 = 0;
    if (x1 > d->w) x1 = d->w; if (y1 > d->h) y1 = d->h;
    for (int y = y0; y < y1; y++) {
        DWORD *row = d->bits + (size_t)y * d->stride;
        for (int x = x0; x < x1; x++) row[x] = c & 0xFFFFFF;
    }
}

BOOL MoveToEx(HDC h, int x, int y, LPPOINT old)
{
    NOVA_DC *d = dc_of(h); if (!d) return FALSE;
    if (old) { old->x = d->cx; old->y = d->cy; }
    d->cx = x; d->cy = y;
    return TRUE;
}

BOOL LineTo(HDC h, int x, int y)
{
    NOVA_DC *d = dc_of(h); if (!d) return FALSE;
    int x0 = d->cx, y0 = d->cy, x1 = x, y1 = y;
    int dx = x1 - x0, dy = y1 - y0;
    int adx = dx < 0 ? -dx : dx, ady = dy < 0 ? -dy : dy;
    int sx = dx < 0 ? -1 : 1, sy = dy < 0 ? -1 : 1;
    int err = (adx > ady ? adx : -ady) / 2, e2;
    COLORREF c = d->has_pen ? d->pen_color : 0;
    for (;;) {
        put(d, x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        e2 = err;
        if (e2 > -adx) { err -= ady; x0 += sx; }
        if (e2 < ady)  { err += adx; y0 += sy; }
    }
    d->cx = x; d->cy = y;
    return TRUE;
}

BOOL Rectangle(HDC h, int l, int t, int r, int b)
{
    NOVA_DC *d = dc_of(h); if (!d) return FALSE;
    if (d->has_brush) fill(d, l, t, r, b, d->brush_color);
    if (d->has_pen) {
        for (int x = l; x < r; x++) { put(d, x, t, d->pen_color); put(d, x, b - 1, d->pen_color); }
        for (int y = t; y < b; y++) { put(d, l, y, d->pen_color); put(d, r - 1, y, d->pen_color); }
    }
    return TRUE;
}

BOOL Ellipse(HDC h, int l, int t, int r, int b)
{
    NOVA_DC *d = dc_of(h); if (!d) return FALSE;
    int cx = (l + r) / 2, cy = (t + b) / 2, ax = (r - l) / 2, ay = (b - t) / 2;
    if (ax <= 0 || ay <= 0) return FALSE;
    for (int y = -ay; y <= ay; y++) {
        for (int x = -ax; x <= ax; x++) {
            long v = (long)x * x * ay * ay + (long)y * y * ax * ax;
            long rr = (long)ax * ax * ay * ay;
            if (v <= rr) { if (d->has_brush) put(d, cx + x, cy + y, d->brush_color); }
        }
    }
    if (d->has_pen) {
        for (int deg = 0; deg < 360; deg++) {
            /* coarse outline via integer parametric steps */
        }
    }
    return TRUE;
}

BOOL PatBlt(HDC h, int x, int y, int w, int hh, DWORD rop)
{
    NOVA_DC *d = dc_of(h); if (!d) return FALSE;
    COLORREF c = rop == BLACKNESS ? 0 : rop == WHITENESS ? 0xFFFFFF : d->brush_color;
    fill(d, x, y, x + w, y + hh, c);
    return TRUE;
}

BOOL BitBlt(HDC dst, int x, int y, int w, int hh, HDC src, int sx, int sy, DWORD rop)
{
    NOVA_DC *dd = dc_of(dst);
    if (!dd) return FALSE;
    if (rop == BLACKNESS || rop == WHITENESS || !src) { fill(dd, x, y, x + w, y + hh, rop == WHITENESS ? 0xFFFFFF : 0); return TRUE; }
    NOVA_DC *sd = dc_of(src);
    for (int j = 0; j < hh; j++)
        for (int i = 0; i < w; i++) {
            int sxx = sx + i, syy = sy + j;
            if (sxx < 0 || syy < 0 || sxx >= sd->w || syy >= sd->h) continue;
            put(dd, x + i, y + j, sd->bits[(size_t)syy * sd->stride + sxx]);
        }
    return TRUE;
}

static void draw_char(NOVA_DC *d, int x, int y, char ch)
{
    if ((unsigned char)ch < 0x20 || (unsigned char)ch > 0x7F) ch = '?';
    const unsigned char *g = g_font + ((unsigned char)ch - 0x20) * 8;
    for (int gy = 0; gy < GLYPH_H; gy++) {
        unsigned char bits = g[gy];
        for (int gx = 0; gx < GLYPH_W; gx++) {
            int on = bits & (1 << gx);
            COLORREF c = on ? d->text_color : d->bk_color;
            if (!on && d->bk_mode == TRANSPARENT) continue;
            for (int sy = 0; sy < SCALE; sy++)
                for (int sx = 0; sx < SCALE; sx++)
                    put(d, x + gx * SCALE + sx, y + gy * SCALE + sy, c);
        }
    }
}

BOOL TextOutA(HDC h, int x, int y, LPCSTR s, int len)
{
    NOVA_DC *d = dc_of(h); if (!d || !s) return FALSE;
    for (int i = 0; i < len && s[i]; i++) draw_char(d, x + i * CELL_W, y, s[i]);
    return TRUE;
}

BOOL TextOutW(HDC h, int x, int y, LPCWSTR s, int len)
{
    NOVA_DC *d = dc_of(h); if (!d || !s) return FALSE;
    for (int i = 0; i < len && s[i]; i++) draw_char(d, x + i * CELL_W, y, s[i] < 0x80 ? (char)s[i] : '?');
    return TRUE;
}

BOOL GetTextExtentPoint32A(HDC h, LPCSTR s, int len, LPSIZE sz)
{
    (void)h;
    if (sz) { sz->cx = len * CELL_W; sz->cy = CELL_H; }
    (void)s;
    return TRUE;
}

/* GDI objects: a small pool of brushes and pens */
typedef struct { int kind; COLORREF color; int width; int used; } GObj;   /* kind 1=brush 2=pen 3=nullbrush 4=nullpen */
static GObj g_stock[20];
static GObj g_pool[256];
static int  g_stock_ready;

static void stock_init(void)
{
    g_stock[WHITE_BRUSH]  = (GObj){ 1, 0xFFFFFF, 0 };
    g_stock[LTGRAY_BRUSH] = (GObj){ 1, 0xC0C0C0, 0 };
    g_stock[GRAY_BRUSH]   = (GObj){ 1, 0x808080, 0 };
    g_stock[DKGRAY_BRUSH] = (GObj){ 1, 0x404040, 0 };
    g_stock[BLACK_BRUSH]  = (GObj){ 1, 0x000000, 0 };
    g_stock[NULL_BRUSH]   = (GObj){ 3, 0, 0 };
    g_stock[WHITE_PEN]    = (GObj){ 2, 0xFFFFFF, 1 };
    g_stock[BLACK_PEN]    = (GObj){ 2, 0x000000, 1 };
    g_stock[NULL_PEN]     = (GObj){ 4, 0, 0 };
    g_stock_ready = 1;
}

HGDIOBJ GetStockObject(int obj)
{
    if (!g_stock_ready) stock_init();
    if (obj < 0 || obj >= 20) return 0;
    if (obj >= OEM_FIXED_FONT) return (HGDIOBJ)&g_stock[0];   /* fonts: a placeholder */
    return (HGDIOBJ)&g_stock[obj];
}

static GObj *pool_alloc(int kind, COLORREF c, int width)
{
    for (int i = 0; i < 256; i++) if (!g_pool[i].used) {
        g_pool[i] = (GObj){ kind, c, width, 1 };
        return &g_pool[i];
    }
    return 0;
}

HBRUSH CreateSolidBrush(COLORREF c) { return (HBRUSH)pool_alloc(1, c, 0); }

HPEN CreatePen(int style, int width, COLORREF c)
{
    return (HPEN)pool_alloc(style == PS_NULL ? 4 : 2, c, width < 1 ? 1 : width);
}

HGDIOBJ SelectObject(HDC h, HGDIOBJ obj)
{
    NOVA_DC *d = dc_of(h);
    GObj *o = (GObj *)obj;
    if (!d || !o) return 0;
    if (o->kind == 1) { d->brush_color = o->color; d->has_brush = 1; }
    else if (o->kind == 3) { d->has_brush = 0; }
    else if (o->kind == 2) { d->pen_color = o->color; d->pen_width = o->width; d->has_pen = 1; }
    else if (o->kind == 4) { d->has_pen = 0; }
    return obj;
}

BOOL DeleteObject(HGDIOBJ obj)
{
    GObj *o = (GObj *)obj;
    if (o >= g_pool && o < g_pool + 256) o->used = 0;    /* stock objects are not freed */
    return TRUE;
}

