static WCHAR *wide(const char *u8)
{
    int n = MultiByteToWideChar(CP_UTF8, 0, u8, -1, NULL, 0);
    WCHAR *w = malloc((size_t)(n > 0 ? n : 1) * sizeof(WCHAR));
    if (!w) return NULL;
    if (n <= 0) { w[0] = 0; return w; }
    MultiByteToWideChar(CP_UTF8, 0, u8, -1, w, n);
    return w;
}

static char *utf8(const WCHAR *w, int len)
{
    int n = WideCharToMultiByte(CP_UTF8, 0, w, len, NULL, 0, NULL, NULL);
    char *s = malloc((size_t)n + 1);
    if (!s) return NULL;
    WideCharToMultiByte(CP_UTF8, 0, w, len, s, n, NULL, NULL);
    s[n] = 0;
    return s;
}

static void push_w(js_State *J, const WCHAR *w)
{
    char *s = utf8(w, -1);
    js_pushstring(J, s ? s : "");
    free(s);
}

