static bool valid_utf8(const unsigned char *p, size_t n)
{
    for (size_t i = 0; i < n;) {
        unsigned c = p[i], k = c < 0x80 ? 0 : (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : 9;
        if (k == 9 || i + k >= n + (k ? 0 : 1)) return false;
        for (unsigned j = 1; j <= k; j++) if ((p[i + j] & 0xC0) != 0x80) return false;
        i += k + 1;
    }
    return true;
}

/* a script file or text file's bytes as UTF-8: UTF-16 with its byte-order
 * mark, UTF-8 (with or without one), else the ANSI code page */
static char *text_of(const unsigned char *p, size_t n)
{
    if (n >= 2 && p[0] == 0xFF && p[1] == 0xFE) return utf8((const WCHAR *)(p + 2), (int)((n - 2) / 2));
    if (n >= 3 && p[0] == 0xEF && p[1] == 0xBB && p[2] == 0xBF) { p += 3; n -= 3; }
    if (n == 0) return calloc(1, 1);
    if (valid_utf8(p, n)) {
        char *s = malloc(n + 1);
        if (s) { memcpy(s, p, n); s[n] = 0; }
        return s;
    }
    int wn = MultiByteToWideChar(CP_ACP, 0, (const char *)p, (int)n, NULL, 0);
    WCHAR *w = malloc((size_t)(wn + 1) * sizeof(WCHAR));
    if (!w) return NULL;
    MultiByteToWideChar(CP_ACP, 0, (const char *)p, (int)n, w, wn);
    char *s = utf8(w, wn);
    free(w);
    return s;
}

static void n_file_read(js_State *J)
{
    WCHAR *p = arg_w(J, 1);
    HANDLE h = CreateFileW(p, GENERIC_READ, FILE_SHARE_READ | FILE_SHARE_WRITE, NULL, OPEN_EXISTING, 0, NULL);
    free(p);
    if (h == INVALID_HANDLE_VALUE) { js_pushnull(J); return; }
    DWORD size = GetFileSize(h, NULL), got = 0;
    unsigned char *data = malloc((size_t)size + 1);
    BOOL ok = data && ReadFile(h, data, size, &got, NULL);
    CloseHandle(h);
    char *s = ok ? text_of(data, got) : NULL;
    free(data);
    if (s) js_pushstring(J, s);
    else js_pushnull(J);
    free(s);
}

static void n_file_write(js_State *J)
{
    WCHAR *p = arg_w(J, 1);
    const char *text = js_tostring(J, 2);
    BOOL append = js_toboolean(J, 3);
    HANDLE h = CreateFileW(p, append ? FILE_APPEND_DATA : GENERIC_WRITE, FILE_SHARE_READ, NULL,
                           append ? OPEN_ALWAYS : CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    free(p);
    if (h == INVALID_HANDLE_VALUE) { js_pushboolean(J, 0); return; }
    DWORD len = (DWORD)strlen(text), wr = 0;
    if (append) SetFilePointer(h, 0, NULL, FILE_END);
    BOOL ok = !len || (WriteFile(h, text, len, &wr, NULL) && wr == len);
    CloseHandle(h);
    js_pushboolean(J, ok);
}

