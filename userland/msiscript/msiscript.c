static void n_list(js_State *J)
{
    WCHAR *dir = arg_w(J, 1), pat[MAX_PATH + 4];
    BOOL dirs = js_toboolean(J, 2);
    _snwprintf(pat, MAX_PATH + 4, L"%s\\*", dir);
    free(dir);
    js_newarray(J);
    WIN32_FIND_DATAW fd;
    HANDLE f = FindFirstFileW(pat, &fd);
    if (f == INVALID_HANDLE_VALUE) return;
    int i = 0;
    do {
        if (!wcscmp(fd.cFileName, L".") || !wcscmp(fd.cFileName, L"..")) continue;
        if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) == !dirs) continue;
        push_w(J, fd.cFileName);
        js_setindex(J, -2, i++);
    } while (FindNextFileW(f, &fd));
    FindClose(f);
}

static void n_special(js_State *J)
{
    WCHAR buf[MAX_PATH];
    int which = js_tointeger(J, 1);
    if (which == 0) GetWindowsDirectoryW(buf, MAX_PATH);
    else if (which == 1) GetSystemDirectoryW(buf, MAX_PATH);
    else {
        GetTempPathW(MAX_PATH, buf);
        size_t n = wcslen(buf);
        if (n > 3 && buf[n - 1] == L'\\') buf[n - 1] = 0;
    }
    push_w(J, buf);
}

static void n_full(js_State *J)
{
    WCHAR *p = arg_w(J, 1), buf[MAX_PATH * 2];
    DWORD n = GetFullPathNameW(p, MAX_PATH * 2, buf, NULL);
    if (!n || n >= MAX_PATH * 2) push_w(J, p);
    else push_w(J, buf);
    free(p);
}

static void n_version(js_State *J)
{
    WCHAR *p = arg_w(J, 1);
    DWORD dummy = 0, size = GetFileVersionInfoSizeW(p, &dummy);
    void *data = size ? malloc(size) : NULL;
    FileVersion *fi = NULL;
    UINT len = 0;
    if (data && GetFileVersionInfoW(p, 0, size, data) && VerQueryValueW(data, L"\\", (void **)&fi, &len) && fi) {
        char v[64];
        snprintf(v, sizeof(v), "%u.%u.%u.%u", (unsigned)HIWORD(fi->dwFileVersionMS), (unsigned)LOWORD(fi->dwFileVersionMS),
                 (unsigned)HIWORD(fi->dwFileVersionLS), (unsigned)LOWORD(fi->dwFileVersionLS));
        js_pushstring(J, v);
    } else js_pushstring(J, "");
    free(data);
    free(p);
}

static void n_env_get(js_State *J)
{
    WCHAR *name = arg_w(J, 1), buf[1024];
    DWORD n = GetEnvironmentVariableW(name, buf, 1024);
    free(name);
    if (!n || n >= 1024) buf[0] = 0;
    push_w(J, buf);
}

static void n_env_set(js_State *J)
{
    WCHAR *name = arg_w(J, 1), *v = arg_w_or_null(J, 2);
    SetEnvironmentVariableW(name, v);
    free(name); free(v);
    js_pushundefined(J);
}

static void n_env_expand(js_State *J)
{
    WCHAR *s = arg_w(J, 1);
    DWORD n = ExpandEnvironmentStringsW(s, NULL, 0);
    WCHAR *buf = malloc((n + 1) * sizeof(WCHAR));
    if (buf && ExpandEnvironmentStringsW(s, buf, n + 1)) push_w(J, buf);
    else push_w(J, s);
    free(buf);
    free(s);
}

static HKEY root_key(int r)
{
    switch (r) {
    case 0: return HKEY_CLASSES_ROOT;
    case 1: return HKEY_CURRENT_USER;
    case 3: return HKEY_USERS;
    case 5: return HKEY_CURRENT_CONFIG;
    default: return HKEY_LOCAL_MACHINE;
    }
}

static void n_reg_key(js_State *J)
{
    WCHAR *key = arg_w(J, 2);
    HKEY k;
    LONG r = RegOpenKeyExW(root_key(js_tointeger(J, 1)), key, 0, KEY_READ, &k);
    free(key);
    if (!r) RegCloseKey(k);
    js_pushboolean(J, !r);
}

static void n_reg_read(js_State *J)
{
    WCHAR *key = arg_w(J, 2), *name = arg_w_or_null(J, 3);
    HKEY k;
    js_pushundefined(J);
    if (RegOpenKeyExW(root_key(js_tointeger(J, 1)), key, 0, KEY_READ, &k)) { free(key); free(name); return; }
    DWORD type = 0, size = 0;
    if (!RegQueryValueExW(k, name, NULL, &type, NULL, &size)) {
        BYTE *data = calloc(1, size + 4);
        if (data && !RegQueryValueExW(k, name, NULL, &type, data, &size)) {
            js_pop(J, 1);
            if (type == REG_DWORD) js_pushnumber(J, *(DWORD *)data);
            else if (type == REG_SZ || type == REG_EXPAND_SZ) push_w(J, (WCHAR *)data);
            else if (type == REG_MULTI_SZ) {
                js_newarray(J);
                int i = 0;
                for (WCHAR *s = (WCHAR *)data; *s; s += wcslen(s) + 1) { push_w(J, s); js_setindex(J, -2, i++); }
            } else {
                js_newarray(J);
                for (DWORD i = 0; i < size; i++) { js_pushnumber(J, data[i]); js_setindex(J, -2, (int)i); }
            }
        }
        free(data);
    }
    RegCloseKey(k);
    free(key);
    free(name);
}

static void n_reg_write(js_State *J)
{
    WCHAR *key = arg_w(J, 2), *name = arg_w_or_null(J, 3);
    const char *type = js_tostring(J, 5);
    HKEY k;
    LONG r = RegCreateKeyExW(root_key(js_tointeger(J, 1)), key, 0, NULL, 0, KEY_WRITE, NULL, &k, NULL);
    if (!r) {
        if (!strcmp(type, "REG_DWORD")) {
            DWORD v = (DWORD)js_tointeger(J, 4);
            r = RegSetValueExW(k, name, 0, REG_DWORD, (BYTE *)&v, 4);
        } else {
            WCHAR *v = arg_w(J, 4);
            r = RegSetValueExW(k, name, 0, !strcmp(type, "REG_EXPAND_SZ") ? REG_EXPAND_SZ : REG_SZ, (BYTE *)v,
                               (DWORD)((wcslen(v) + 1) * sizeof(WCHAR)));
            free(v);
        }
        RegCloseKey(k);
    }
    free(key);
    free(name);
    js_pushboolean(J, !r);
}

static void n_reg_delete(js_State *J)
{
    WCHAR *key = arg_w(J, 2), *name = arg_w_or_null(J, 3);
    HKEY root = root_key(js_tointeger(J, 1)), k;
    LONG r;
    if (!name) r = RegDeleteKeyW(root, key);
    else if (!(r = RegOpenKeyExW(root, key, 0, KEY_WRITE, &k))) { r = RegDeleteValueW(k, name); RegCloseKey(k); }
    free(key);
    free(name);
    js_pushboolean(J, !r);
}

static void n_run(js_State *J)
{
    WCHAR *cmd = arg_w(J, 1);
    STARTUPINFOW si;
    PROCESS_INFORMATION pi;
    memset(&si, 0, sizeof(si));
    si.cb = sizeof(si);
    say("Running %s", js_tostring(J, 1));
    BOOL ok = CreateProcessW(NULL, cmd, NULL, NULL, FALSE, 0, NULL, NULL, &si, &pi);
    free(cmd);
    if (!ok) check(J, GetLastError(), "WScript.Shell.Run");
    DWORD code = 0;
    if (js_toboolean(J, 2)) {
        WaitForSingleObject(pi.hProcess, INFINITE);
        GetExitCodeProcess(pi.hProcess, &code);
    }
    CloseHandle(pi.hThread);
    CloseHandle(pi.hProcess);
    js_pushnumber(J, code);
}

